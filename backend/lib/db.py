import psycopg2 as pg
from backend.settings import PG_PASSWORD, PG_USER
from psycopg2.extras import execute_values


def connect():
    conn = pg.connect(host='localhost', user=PG_USER, password=PG_PASSWORD, database="backend")
    return conn


def setup(wordassoc=None, responses=None, affixes=None, norms=None, prevalences=None, concreteness=None, age=None):
    # "id","participantID","created_at","age","nativeLanguage","gender","education","city","country","section","cue","R1Raw","R2Raw","R3Raw","R1","R2","R3"
    conn = connect()
    cur = conn.cursor()

    if wordassoc:
        # ---------------------------------------------- wordassoc table ----------------------------------------------#

        cur.execute("""DROP TABLE IF EXISTS wordassoc""")
        cur.execute("""CREATE TABLE IF NOT EXISTS wordassoc(
        id integer PRIMARY KEY,
        participantID integer,
        created_at text,
        age text,
        nativeLanguage text,
        gender text,
        education text,
        city text,
        country text,
        section text,
        cue text,
        R1Raw text,
        R2Raw text,
        R3Raw text,
        R1 text,
        R2 text,
        R3 text)""")
        conn.commit()

    if responses:
        # ---------------------------------------------- responses table ----------------------------------------------#
        cur.execute("""CREATE TABLE IF NOT EXISTS responses(
        id integer PRIMARY KEY,
        created timestamp,
        cue text,
        response text,
        time_duration int)
        """)
        conn.commit()

    if affixes:
        # ---------------------------------------------- affixes table ------------------------------------------------#
        cur.execute("""DROP TABLE IF EXISTS affixes""")
        cur.execute("""CREATE TABLE IF NOT EXISTS affixes(
        id integer GENERATED BY DEFAULT AS IDENTITY,
        affix text,
        type text)
        """)
        conn.commit()

    if norms:
        # ---------------------------------------------- norms table --------------------------------------------------#

        # ZUCCHINI, NASTY, YES, 148, 3, .020, 0.000, 0.0000, .0020, 0, 0, 2.0, 0, 13, 0, �, , N, 2.50, .17, .007, 1, 12, 5, 2.63, , AJ, 2.58, .42, .030, 1
        cur.execute("""DROP TABLE IF EXISTS norms""")
        cur.execute("""CREATE TABLE IF NOT EXISTS norms(
        id integer GENERATED BY DEFAULT AS IDENTITY,
        cue text,
        response text,
        normed bool,
        groupsize smallint,
        participants_producing_response smallint,
        forward_strength decimal,
        cue_set_size decimal,
        cue_frequency decimal,
        cue_concreteness decimal,
        cue_homograph bool,
        cue_part_of_speech bool,
        cue_connectivity decimal,
        cue_resonant_probability decimal,
        cue_resonant_strength decimal,
        cue_use_code bool,
        response_set_size decimal,
        response_frequency decimal,
        response_concreteness decimal,
        response_homograph bool,
        response_part_of_speech bool,
        response_connectivity decimal,
        response_resonant_probability decimal,
        response_resonant_strength decimal,
        response_use_code bool
        )
        """)
        conn.commit()

    if prevalences:
        # ---------------------------------------------- prevalences table --------------------------------------------#
        # word', 'pknown', 'nobs', 'prevalence', 'freqzipfus
        cur.execute("""DROP TABLE IF EXISTS prevalences""")
        cur.execute("""CREATE TABLE IF NOT EXISTS prevalences(
        id integer GENERATED BY DEFAULT AS IDENTITY,
        word text,
        pknown DECIMAL,
        nobs DECIMAL,
        prevalence DECIMAL,
        freqzipfus DECIMAL)
        """)
        conn.commit()

    if concreteness:
        # ---------------------------------------------- concreteness table -------------------------------------------#
        #  'word', 'bigram', 'concreteness_measure', 'concreteness_standard_dev', 'unknown', 'total', 'percent_known',
        #             'subtlex', 'dom_pos')
        cur.execute("""DROP TABLE IF EXISTS concreteness""")
        cur.execute("""CREATE TABLE IF NOT EXISTS concreteness(
        id integer GENERATED BY DEFAULT AS IDENTITY,
        word text,
        bigram DECIMAL,
        concreteness_measure DECIMAL,
        concreteness_standard_dev DECIMAL,
        unknown INT,
        total INT,
        percent_known DECIMAL,
        subtlex INT,
        dom_pos TEXT)
        """)
        conn.commit()

    if age:
        # ---------------------------------------------- acquisition_age -------------------------------------------#

        cur.execute("""DROP TABLE IF EXISTS acquisition_age""")
        cur.execute("""CREATE TABLE IF NOT EXISTS acquisition_age(
        id integer GENERATED BY DEFAULT AS IDENTITY,
        word text,
        alternative_spelling text,
        freq_pm decimal,
        dom_pos_subtlex text,
        num_letters int,
        num_phon int,
        num_syllables int,
        lemma_highest_pos text,
        aoa_kup_lemma decimal,
        percent_known_lemma decimal)
        """)
        conn.commit()


def execute_values_wrap(cur, table, fieldnametuple, values):
    fieldnames = '(%s)' % ','.join(fieldnametuple).lower()
    query = "INSERT INTO %(table)s %(fieldnames)s VALUES" % {'table': table, 'fieldnames': fieldnames}
    query = ' '.join([query, "%s"])
    result = execute_values(cur, query, values)
    return result


def get_cue_response_pairs(min_length=None, limit=None):
    conn = connect()
    cur = conn.cursor(cursor_factory=pg.extras.DictCursor)
    query = """ SELECT participantID, cue, r1raw AS response_raw, r1 AS response, count(r1) AS count
                    FROM wordassoc
                    WHERE r1 != 'Unknown word'
                    AND LENGTH(r1) > 3
                    AND LENGTH(cue) > 3
                    GROUP BY participantID, cue, r1, r1raw"""
    if limit:
        query += """ LIMIT %s""" % str(int(limit))
    cur.execute(query)
    return cur


def get_affixes():
    conn = connect()
    cur = conn.cursor(cursor_factory=pg.extras.DictCursor)
    query = """ SELECT affix, type
                FROM affixes"""
    cur.execute(query)
    return [dict(x) for x in cur]


def get_common_norms():
    conn = connect()
    cur = conn.cursor(cursor_factory=pg.extras.DictCursor)
    query = """ SELECT cue, response
                FROM norms
                WHERE forward_strength > 0.4"""
    cur.execute(query)
    cue_pair_dict = {}
    for pair in cur:
        cue_pair_dict.setdefault(pair['cue'], [])
        cue_pair_dict[pair['cue']].append(pair['response'])
    return cue_pair_dict


def get_prevalences():
    conn = connect()
    cur = conn.cursor(cursor_factory=pg.extras.DictCursor)
    query = """ SELECT word, prevalence
                FROM prevalences
    """
    cur.execute(query)
    return {x['word']: x['prevalence'] for x in cur}


def get_concretenesses():
    conn = connect()
    cur = conn.cursor(cursor_factory=pg.extras.DictCursor)
    query = """ SELECT word, concreteness_measure as concreteness
                FROM concreteness
    """
    cur.execute(query)
    return {x['word']: x['concreteness'] for x in cur}


def get_acquisition_ages():
    conn = connect()
    cur = conn.cursor(cursor_factory=pg.extras.DictCursor)
    query = """ SELECT word, alternative_spelling as word_alternative, lemma_highest_pos as word_lemma, aoa_kup_lemma as age
                FROM acquisition_age
    """
    cur.execute(query)
    age_dict = {}
    for x in cur:
        word_set = {x['word'], x['word_alternative'], x['word_lemma']}
        for w in list(word_set):
            age_dict[w] = x['age']
    return age_dict
