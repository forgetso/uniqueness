def quote_values_for_insert(params):
    return "".join(["('", "'),('".join(params), "')"])


def setup():
    parser = argparse.ArgumentParser(description="DB setup")
    parser.add_argument(
        "--responses", action="store_true", help="Delete the responses table"
    )
    parser.add_argument(
        "--senses", action="store_true", help="Delete and repopulate the senses table"
    )
    parser.add_argument(
        "--users", action="store_true", help="Delete and recreate the users table"
    )
    parser.add_argument(
        "--measures", action="store_true", help="Delete and recreate the measures table"
    )
    args = parser.parse_args()
    db_setup(
        responses=args.responses,
        senses=args.senses,
        users=args.users,
        measures=args.measures,
    )


if __name__ == "__main__":
    setup()
